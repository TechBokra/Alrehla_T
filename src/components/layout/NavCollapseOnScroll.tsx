'use client';

import { useEffect } from 'react';

/**
 * يخفي **صفّ قائمة الموقع** وإنت نازل، ويرجّعه وإنت طالع.
 *
 * ── العطل اللي اتعمل عشانه ──────────────────────────────────
 *
 * على شاشة ضيّقة الزائر بيشوف **أربع طبقات قبل أول كلمة محتوى**:
 *
 *     شريط التنبيه · الهيدر · صفّ قائمة الموقع · صفّ قائمة القسم
 *
 * والصفّان بيعملان حاجتين مختلفتين: قائمة الموقع بتقول «أنا فين في
 * الموقع» وبتتستعمل **مرة**، وقائمة القسم بتقول «أروح فين جوّه
 * القسم» وبتتستعمل **طول ما إنت هنا**.
 *
 * فاللي بيتشال وقت القراءة هو الأولى، والتانية بتفضل لازقة.
 *
 * ── إزاي بيشتغل ─────────────────────────────────────────────
 *
 * بيحطّ `data-nav-collapsed` على `<html>`، والتنسيق كله في
 * `globals.css`. المكوّن ده **مابيرسمش حاجة** — بيقلّب سمة وبس.
 *
 * ⚠️ **ليه سمة على `<html>` مش حالة في React؟** عشان العنصرين
 *    اللي بيتأثروا (صفّ القائمة في الهيدر، وارتفاع لزوق قائمة
 *    القسم) في **مكوّنين مختلفين** — وتمرير الحالة بينهم كان
 *    هيحوّل الهيدر لمكوّن عميل بالكامل، وهو دلوقتي مكوّن خادم
 *    عن قصد (مكتوب في تعليقه إن ده بيخلّي كل صفحة في الموقع
 *    قابلة للتخزين المؤقت).
 *
 * ── وقواعد سلوكه ────────────────────────────────────────────
 *
 * ⚠️ **مابيتخفيش إلا بعد 120 بكسل.** من غير العتبة دي، أي حركة
 *    صغيرة فوق بتخفي القائمة والزائر لسه في أول الصفحة.
 *
 * ⚠️ **وعتبة 8 بكسل بين القراءتين.** التمرير بالإصبع بيدّي قراءات
 *    متذبذبة بالبكسل الواحد، ومن غير العتبة القائمة بترفرف.
 *
 * ⚠️ **وبيرجع فورًا عند الطلوع** — مش عند الوصول لأول الصفحة.
 *    اللي بيطلع بيدوّر على حاجة، والقائمة لازم تكون تحت إيده.
 */
export function NavCollapseOnScroll() {
  useEffect(() => {
    const root = document.documentElement;
    const THRESHOLD = 120; // مافيش إخفاء قبلها
    const JITTER = 8; // أقل فرق يتحسب حركة

    let last = window.scrollY;
    let frame = 0;

    const apply = () => {
      frame = 0;
      const y = window.scrollY;
      const delta = y - last;

      if (Math.abs(delta) < JITTER) return;

      if (y < THRESHOLD) {
        root.removeAttribute('data-nav-collapsed');
      } else if (delta > 0) {
        root.setAttribute('data-nav-collapsed', '');
      } else {
        root.removeAttribute('data-nav-collapsed');
      }
      last = y;
    };

    const onScroll = () => {
      // القراءة مرة واحدة في الإطار: `scroll` بيتنادى عشرات المرات
      // في الثانية، و`scrollY` قراءة تخطيط.
      if (!frame) frame = requestAnimationFrame(apply);
    };

    window.addEventListener('scroll', onScroll, { passive: true });
    return () => {
      window.removeEventListener('scroll', onScroll);
      if (frame) cancelAnimationFrame(frame);
      // ⚠️ التنظيف بيشيل السمة: من غيره الانتقال لصفحة تانية وهي
      //    مطوية بيسيب القائمة مخفية بلا سبب.
      root.removeAttribute('data-nav-collapsed');
    };
  }, []);

  return null;
}
