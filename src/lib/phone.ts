/**
 * أرقام التليفون — تنظيف وتحقّق.
 *
 * ── العطل اللي بيقفله ───────────────────────────────────────
 *
 * ⚠️ **`type="tel"` مش بيمنع الحروف.**
 *
 *    ودي مفاجأة لأي حد شايف الاسم. `type="tel"` بيغيّر **لوحة
 *    المفاتيح على الموبايل** وبس — المتصفح بيقبل «أهلاً» في الخانة
 *    زي ما بيقبل «01012345678»، وبيرسلها للخادم، والخادم بيخزّنها.
 *
 *    والنتيجة: الإدارة بتفتح طلب عليه رقم تليفون مكتوب فيه كلام،
 *    وماتقدرش تتواصل — والعميل فاكر إنه سجّل بياناته صح.
 *
 * ⚠️ **و`pattern` في الواجهة مش دليل كمان** (قاعدة «ع»): المتصفح
 *    بيمنع الإرسال، والطلب المباشر للخادم بيعدّي. فالتحقّق الحقيقي
 *    هنا، والواجهة بتحسّن التجربة وبس.
 *
 * ── إيه اللي بيتقبل ─────────────────────────────────────────
 *
 * أرقام، ومسافات وشرط وأقواس (بيتشالوا)، و`+` في الأول بس —
 * عشان الرقم الدولي. الطول بين 7 و15 رقمًا: 15 هو الحد الأقصى
 * في المعيار الدولي E.164، و7 أقصر رقم محلي معقول.
 *
 * ⚠️ **ومفيش فحص أدق من كده عن قصد.** الأرقام المصرية بتبدأ
 *    `01` بـ11 رقمًا، بس المنصة بتستقبل من الخليج كمان، وأي قاعدة
 *    أضيق هتوقّع أرقامًا صحيحة. الرفض الكاذب على رقم تليفون بيخسّر
 *    عميلًا — والرقم الغلط الإدارة بتتصل بيه وتكتشفه.
 */

/** الأرقام العربية (٠١٢…) والفارسية (۰۱۲…) ← 012… — العميل بيكتب بكيبورد عربي. */
function toLatinDigits(value: string): string {
  return value
    .replace(/[\u0660-\u0669]/g, (d) => String(d.charCodeAt(0) - 0x0660))
    .replace(/[\u06F0-\u06F9]/g, (d) => String(d.charCodeAt(0) - 0x06f0));
}

/** بيشيل التنسيق ويسيب الأرقام و`+` الأولى. */
export function normalizePhone(value: string | null | undefined): string {
  if (typeof value !== 'string') return '';
  const trimmed = toLatinDigits(value.trim());
  const plus = trimmed.startsWith('+') ? '+' : '';
  return plus + trimmed.replace(/[^\d]/g, '');
}

/**
 * ⚠️ **بيفحص اللي العميل كتبه نفسه، مش بعد التنظيف** (اختبار «إنها لك» 3.8):
 *    كان بيشيل الحروف الأول وبعدين يعدّ الأرقام — فـ«abc01012345678»
 *    كانت بتعدّي. دلوقتي أي حرف = رفض. المسموح: أرقام (لاتيني أو عربي)،
 *    ومسافات وشرط ونقط وأقواس، و`+` في الأول بس.
 */
export function isValidPhone(value: string | null | undefined): boolean {
  if (typeof value !== 'string') return false;
  const raw = toLatinDigits(value.trim());
  if (!/^\+?[0-9\s().-]+$/.test(raw)) return false;
  const digits = normalizePhone(raw).replace('+', '');
  // «٠٠٠٠٠٠٠٠٠٠» بتعدّي فحص الطول وهي مش رقم — ودي الحاجة الوحيدة
  // اللي بنضيفها على الحد الأدنى، لأنها مستحيلة في أي بلد.
  if (new Set(digits).size === 1) return false;
  return digits.length >= 7 && digits.length <= 15;
}

