import 'server-only';
import { revalidatePath } from 'next/cache';

/**
 * تحديث صفحات الموقع العامة بعد أي تعديل بيظهر فيها — **من مكان واحد**.
 *
 * ── المشكلة ─────────────────────────────────────────────────
 *
 * الصفحات العامة متخزّنة لحد ساعة (أسرع للزوّار). وكل عملية كانت بتقول
 * بنفسها «حدّث الصفحات دي»، والقايمة كانت بتتنسي: تعديل منتج مابيحدّثش
 * الرئيسية، أسعار المدربين مابتحدّثش صفحاتهم، مقدّمي الخدمة مابيحدّثوش
 * صفحة الخدمة… فالزائر يشوف سعر قديم أو منتج اتشال لحد ساعة.
 *
 * ── الحل ────────────────────────────────────────────────────
 *
 * أي تعديل بيظهر للزوّار = **كل الصفحات العامة بتتحدّث**. مفيش قايمة
 * تتنسي. التمن: أول زائر بعد التعديل بيستنى الصفحة تتبني (أقل من ثانيتين)،
 * وده بيحصل بس لما الإدارة تعدّل محتوى — مش مع كل طلب أو حجز.
 *
 * ⚠️ صفحات اللوحات والحساب **مش** هنا: دي بتتبني مع كل فتحة أصلًا،
 *    وكل عملية بتحدّث الشاشة اللي هي فيها زي ما كانت.
 */
export function refreshPublicPages(): void {
  revalidatePath('/', 'layout');
}
