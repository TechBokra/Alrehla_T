/**
 * نصوص الموقع القابلة للتعديل من لوحة الإدارة.
 *
 * كل نص هنا كان مكتوبًا في الكود — يعني تغيير كلمة واحدة كان بيحتاج مبرمج.
 * الملف ده بيحوّلهم لخانات ليها اسم ومكان معروف، والإدارة بتعدّلها من
 * «محتوى الصفحات».
 *
 * القاعدة المهمة: النص الأصلي مكتوب هنا كـ `fallback`. لو الخانة مش متخزّنة
 * في قاعدة البيانات، الصفحة بتعرض النص الأصلي — فالموقع عمره ما بيفضى،
 * والإدارة بتقدر ترجّع أي نص لأصله بضغطة.
 *
 * رسائل النماذج وخطوات الدفع **مش** هنا عن قصد: دي واجهة مش محتوى،
 * وتعديلها بيكسر الموقع أكتر ما بيفيد.
 *
 * أزرار الصفحة الرئيسية **استثناء**: نصّها دعوة تسويقية بتتغيّر بتغيّر
 * الحملة، فاتفتحت للتعديل. الروابط نفسها مقفولة — النص بس هو اللي
 * بيتعدّل.
 */

export type ContentFieldType =
  /** سطر واحد — عنوان أو زر */
  | 'text'
  /** فقرة */
  | 'longtext'
  /** نص طويل بتنسيق مبسّط (عناوين ونقاط) */
  | 'richtext';

export interface ContentField {
  key: string;
  label: string;
  type: ContentFieldType;
  /** النص الظاهر على الموقع دلوقتي. */
  fallback: string;
  /** شرح إضافي يظهر تحت الخانة عند اللزوم. */
  hint?: string;
}

export interface ContentGroup {
  id: string;
  /** اسم الصفحة كما يعرفها صاحب الموقع. */
  title: string;
  /** مسارها على الموقع — عشان يقدر يفتحها ويشوف التغيير. */
  path: string;
  /** ملاحظة فوق الخانات — مثلًا إن جزء من المحتوى بيتعدّل من مكان تاني. */
  note?: string;
  fields: ContentField[];
}

