/**
 * منع حفظ الصور — **القرار وحده، بلا شاشة** (عشان يتختبر).
 *
 * ═══════════════════════════════════════════════════════════
 * ⚠️ اقرا ده قبل ما تفتكر إن الصور بقت محمية
 * ═══════════════════════════════════════════════════════════
 *
 * **أي صورة ظاهرة في المتصفح اتحمّلت فعلًا على جهاز الزائر.** ده
 * مش عيب في الموقع، ده تعريف «عرض صورة على الإنترنت». فمفيش كود
 * يقدر يمنع:
 *   • لقطة الشاشة (زرار في كل تليفون)
 *   • أدوات المطوّر في المتصفح، أو فتح رابط الصورة من مصدر الصفحة
 *
 * اللي الكود ده بيعمله **إنه بيقفل الطرق السهلة** — وهي اللي
 * بيستعملها ٩٩٪ من الناس:
 *   • الضغط يمين ← «حفظ الصورة» (كمبيوتر)
 *   • الضغط الطويل ← «تنزيل الصورة» (أندرويد وآيفون)
 *   • سحب الصورة لسطح المكتب
 *
 * يعني ده **ردع لا حماية**. لو المطلوب إن الصورة المنسوخة تفضل
 * بتقول مصدرها، الحل **علامة مائية** على الصورة نفسها من Cloudinary
 * — وده قرار منفصل.
 *
 * ── ليه على الصور بس مش على الصفحة كلها ─────────────────────
 *
 * قفل الضغط يمين على الصفحة كلها بيكسر حاجات حقيقية: «نسخ» رقم
 * التحويل من صفحة الدفع، «فتح في تبويب جديد» على أي رابط، والتدقيق
 * الإملائي في خانات الكتابة. والطلب كان الصور.
 */

/** العنصر اللي بيتفحص — أقل شكل من `Element` عشان يتختبر من غير متصفح. */
export type GuardTarget = {
  tagName?: string;
  closest?: (selector: string) => unknown;
};

/**
 * الوسوم اللي بتتقفل. `picture` و`svg image` بتتعامل زي الصورة، و
 * `[data-protect-media]` لأي عنصر فيه صورة خلفية (`background-image`)
 * — الضغط يمين عليه بيدّي «حفظ الصورة» في بعض المتصفحات.
 */
const PROTECTED_SELECTOR = 'img, picture, video, [data-protect-media]';

/**
 * ⚠️ **الاستثناء بعلامة صريحة لا بالمكان.** لو في يوم الإدارة احتاجت
 *    تحفظ صورة إيصال دفع، الصورة دي بتاخد `data-allow-save` — مش
 *    «الحماية مقفولة في لوحة التحكم كلها»، لأن الاستثناء الواسع بينسى
 *    صورًا مش المفروض تتحفظ.
 */
const ALLOW_SELECTOR = '[data-allow-save]';

export function isProtectedMedia(target: GuardTarget | null | undefined): boolean {
  if (!target || typeof target.closest !== 'function') return false;
  if (target.closest(ALLOW_SELECTOR)) return false;
  return Boolean(target.closest(PROTECTED_SELECTOR));
}
