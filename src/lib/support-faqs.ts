/**
 * أسئلة صفحة الدعم — بتتكتب من «إدارة المحتوى ← الدعم والمساعدة»
 * كنص عادي، والصفحة بتحوّله لأسئلة وإجابات.
 *
 * الشكل:
 *
 *     س: السؤال
 *     ج: الإجابة (ممكن تكمل في أكتر من سطر)
 *
 *     س: سؤال تاني
 *     ج: …
 *
 * `{مدة_الملفات}` جوّه الإجابة بتتبدّل بعدد أيام حفظ الملفات من
 * «الإعدادات العامة» — عشان الرقم مايتلخبطش لو اتغيّر.
 *
 * ⚠️ من غير React — عشان يتختبر.
 */

export type Faq = { q: string; a: string };

/** النص ← قايمة أسئلة. السطر اللي مش بادئ بـ«س:» أو «ج:» بيكمّل اللي قبله. */
export function parseFaqText(text: string, vars: Record<string, string | number> = {}): Faq[] {
  const out: Faq[] = [];
  let cur: { q: string; a: string } | null = null;
  let field: 'q' | 'a' | null = null;
  for (const raw of (text ?? '').replace(/\r/g, '').split('\n')) {
    const line = raw.trim();
    const q = /^س\s*[:：]\s*(.*)$/.exec(line);
    const a = /^ج\s*[:：]\s*(.*)$/.exec(line);
    if (q) {
      if (cur && cur.q && cur.a) out.push(cur);
      cur = { q: q[1], a: '' };
      field = 'q';
    } else if (a && cur) {
      cur.a = a[1];
      field = 'a';
    } else if (line && cur && field) {
      cur[field] = `${cur[field]}${field === 'a' ? '\n' : ' '}${line}`;
    }
  }
  if (cur && cur.q && cur.a) out.push(cur);

  const fill = (s: string) =>
    s.replace(/\{([^{}\s]+)\}/g, (m, name: string) => (name in vars ? String(vars[name]) : m));
  return out.map((f) => ({ q: fill(f.q.trim()), a: fill(f.a.trim()) }));
}

