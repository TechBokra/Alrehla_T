/**
 * تسجيل الجلسات — **مصدر واحد للنصّ والأرقام**.
 *
 * ── ليه ملف لوحده ───────────────────────────────────────────
 *
 * مدة الاحتفاظ بالتسجيل رقم بيظهر في **خمس أماكن**: شاشة الحجز،
 * وسياسة الخصوصية، وشاشة الجلسة عند المدرب، وشاشة ولي الأمر،
 * وشاشة الإعدادات. ولو اتكتب في كل مكان على حدة، أول تعديل في
 * الإعدادات بيخلّي أربع شاشات **بتقول رقمًا غير الحقيقي**.
 *
 * ⚠️ **وده مش عيب شكلي هنا.** الرقم ده وعد لولي أمر عن تسجيل فيه
 *    ابنه. صفحة بتقول «أسبوع» وتانية بتقول «شهر» مش تناقض في
 *    التصميم — دي مشكلة ثقة.
 *
 * فالرقم بيتقرا من الإعدادات، والجُمَل كلها بتتبني من هنا.
 */

/** الافتراضي لو الإعدادات لسه ما اتظبطتش. */
export const DEFAULT_RETENTION_DAYS = 30;

/** الخيارات اللي بتظهر للإدارة. */
export const RETENTION_OPTIONS = [
  { days: 7, label: 'أسبوع' },
  { days: 30, label: 'شهر' },
  { days: 60, label: 'شهرين' },
  { days: 90, label: 'ثلاثة شهور' },
] as const;

export type SessionRecordingSettings = {
  enabled: boolean;
  retentionDays: number;
};

export const DEFAULT_RECORDING_SETTINGS: SessionRecordingSettings = {
  enabled: false,
  retentionDays: DEFAULT_RETENTION_DAYS,
};

/**
 * المدة بالعربي: «أسبوع» أحسن من «٧ أيام» لولي أمر بيقرا بسرعة.
 *
 * ⚠️ **وأي رقم مش في القايمة بيتعرض بالأيام** — مش بيتقرّب لأقرب
 *    خيار. لو الإدارة كتبت ١٤، ولي الأمر لازم يقرا «١٤ يومًا» لا
 *    «أسبوع».
 */
export function retentionLabel(days: number): string {
  const known = RETENTION_OPTIONS.find((o) => o.days === days);
  if (known) return known.label;
  if (days === 1) return 'يوم واحد';
  if (days === 2) return 'يومين';
  if (days <= 10) return `${days} أيام`;
  return `${days} يومًا`;
}

/**
 * العلامة اللي بتتبدّل بالمدة داخل نصوص لوحة التحكم.
 *
 * ⚠️ **المدة مابتتكتبش في النص نفسه** — عشان صفحة ما تقولش «شهر»
 *    والإعدادات فيها «أسبوع». الإدارة بتكتب `{المدة}` والرقم
 *    بيتحط وقت العرض.
 */
export const DURATION_TOKEN = '{المدة}';

/**
 * بيحطّ المدة مكان العلامة في نص جاي من لوحة التحكم.
 *
 * ⚠️ **ولو العلامة مش موجودة، النص بيتعرض زي ما هو.** مابنضيفش
 *    المدة في الآخر ولا بنرمي خطأ: الإدارة اللي كتبت النص أدرى،
 *    وشاشة الإعدادات بتحذّر إن المدة هتختفي.
 */
export function withRetention(template: string, days: number): string {
  return template.split(DURATION_TOKEN).join(retentionLabel(days));
}

/**
 * الجملة اللي بتظهر على الشاشات قبل الحجز وأثناء المتابعة.
 *
 * `template` بييجي من لوحة التحكم. من غيره بيرجع النص الأصلي —
 * فالشاشة عمرها ما تفضى.
 */
export function recordingNotice(days: number, template?: string): string {
  const text =
    template?.trim() ||
    `الجلسات بتتسجّل لأغراض الأمان ومراجعة جودة التدريب، وبتتحذف تلقائيًّا بعد ${DURATION_TOKEN}. التسجيل مابيتنشرش ومابيتشافش إلا من إدارة المنصة.`;
  return withRetention(text, days);
}

/** الجملة اللي جنب مربّع الموافقة في شاشة الحجز. */
export function consentLabel(days: number, template?: string): string {
  const text =
    template?.trim() ||
    `أوافق على تسجيل الجلسات وحفظها لمدة ${DURATION_TOKEN} لأغراض الأمان ومراجعة الجودة.`;
  return withRetention(text, days);
}

/**
 * قسم سياسة الخصوصية — بيتولّد بالرقم الحالي.
 *
 * ⚠️ **النص ده بيتحط في لوحة التحكم، مش بيتعرض من هنا.** سياسة
 *    الخصوصية بتتقرا من `site_settings`/`site_content` لأن تعديلها
 *    قرار قانوني لا برمجي. الدالة دي بتجهّز النص الصح عشان الإدارة
 *    تلزقه، ولو الرقم اتغيّر في الإعدادات **لازم النص يتحدّث برضه** —
 *    الإعدادات مابتعدّلش السياسة لوحدها، وده مقصود.
 */
export function privacyRecordingSection(days: number): string {
  return `## تسجيل الجلسات

- **بنسجّل جلسات الفيديو التعليمية** في برنامج «بداية الرحلة». التسجيل مش اختياريًّا في الجلسة: كل جلسة بتتسجّل.
- **ليه:** سلامة الطفل، ومراجعة جودة التدريب، والرجوع للتسجيل لو حصلت شكوى.
- **مين بيشوفه:** إدارة المنصة وحدها. مابيتنشرش، ومابيتبعتش لطرف تالت، ومابيتستخدمش في أي دعاية.
- **قد إيه بيفضل:** ${retentionLabel(days)} من تاريخ الجلسة، وبعدها بيتحذف.
- **حقّك:** تقدر تطلب حذف تسجيل جلسة ابنك قبل انتهاء المدة، أو تطلب الاطلاع عليه، عبر مركز الدعم.
- بنقول لولي الأمر ده **قبل الحجز والدفع**، وموافقته شرط لإتمام الحجز.`;
}
