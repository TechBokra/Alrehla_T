/**
 * الرسالة اللي الإدارة بتبعتها لصاحب حساب جديد أو لحساب اتعمله رمز جديد.
 *
 * ── ليه ملف واحد ────────────────────────────────────────────
 *
 * كانت مكتوبة **أربع مرات** في أربع شاشات (مدرب جديد، طلب انضمام،
 * صفحة المدرب، صفحة المستخدم) بأربع صيغ مختلفة — وتلاتة منهم كانوا
 * بيبعتوا رابط `/login` **وهو مش موجود في الموقع خالص** (المسار
 * `/sign-in`). يعني كل مدرب اتعمل له رمز من صفحته استلم رابط بيوديه
 * على 404، ويرجع يقول «الرابط مش شغّال».
 *
 * فالنص بقى هنا، والشاشات بتنادي. ولو اتغيّر، بيتغيّر مرة واحدة.
 *
 * ⚠️ **الرمز في سطر لوحده، ومن غير أي علامة بعده.** الرسالة عربية
 *    (RTL) والرمز لاتيني (LTR): لو جه وسط سطر عربي أو جابت نقطة
 *    وراه، ترتيبه البصري بيتبهدل والنقطة بتتنسخ معاه — فالمستلم
 *    يدخل برمز غلط ويقول إن «البيانات مش شغّالة».
 *
 * ⚠️ **ومفيش كلام عن صلاحية بتنتهي.** الرمز هو كلمة مرور الحساب
 *    المؤقتة ومالهاش مدة؛ اللي بيبطّلها إن صاحبه يحطّ كلمة مروره.
 *    فالرسالة بتربط الإبطال بالخطوة دي، مش بوقت مش موجود.
 *
 * ⚠️ **والصيغة محايدة قدر الإمكان** («حضرتك»، «نوّرت») — القالب مش
 *    عارف صاحب الحساب راجل ولا ست، ونص مذكّر صريح بيوصل غلط لنص
 *    المدربين تقريبًا.
 */

/** مسار الدخول. **مش `/login`** — ده مش موجود. */
export const SIGN_IN_PATH = '/sign-in';

export type AccountMessageParts = {
  /** الرمز المؤقت — بيتحط في سطر لوحده. */
  code: string;
  email: string;
  /** رابط الدخول كامل. من غيره السطر مابيظهرش بدل ما يظهر ناقص. */
  loginUrl?: string;
  /** سطر أول الرسالة. الافتراضي ترحيب محايد. */
  greeting?: string;
  /** اللي هيلاقيه بعد ما يحدّد كلمة مروره — لو فيه حاجة محددة. */
  nextStep?: string;
};

export function accountMessage(parts: AccountMessageParts): string {
  return [
    parts.greeting?.trim() || 'أهلًا بحضرتك — نوّرت الرحلة 🌿',
    '',
    'حسابك على المنصة بقى جاهز، وفاضل خطوة واحدة بس.',
    '',
    parts.loginUrl ? `رابط الدخول: ${parts.loginUrl}` : null,
    `البريد: ${parts.email}`,
    '',
    'الرمز المؤقت',
    parts.code,
    '',
    'أول دخول بالرمز، الموقع هيوقفك على شاشة تحطّ فيها كلمة مرورك إنت. وبعدها الرمز مابقاش ينفع، وكلمة المرور مايعرفهاش غيرك — ولا إحنا.',
    parts.nextStep?.trim() ? '' : null,
    parts.nextStep?.trim() || null,
    '',
    'وأي حاجة تحتاجها، إحنا موجودين. مستنيينك 🌱',
    'فريق الرحلة',
  ]
    .filter((line) => line !== null)
    .join('\n');
}

/** ترحيب بالاسم — بيرجّع الافتراضي لو الاسم فاضي. */
export function greetByName(name?: string | null): string | undefined {
  const trimmed = name?.trim();
  return trimmed ? `أهلًا ${trimmed} — نوّرت الرحلة 🌿` : undefined;
}
