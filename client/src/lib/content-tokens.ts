/**
 * العلامات اللي بتتبدّل بأرقام الإعدادات داخل نصوص لوحة التحكم.
 *
 * ── ليه الأرقام مابتتكتبش في النص ───────────────────────────
 *
 * مدة حفظ التسجيلات ومدة حفظ الملفات **إعدادات بتتغيّر من اللوحة**،
 * والسياسة والأسئلة نصوص بتتكتب بالإيد. لو الرقم مكتوب في النص،
 * أول ما الإدارة تغيّر الإعداد تبقى **سياسة الخصوصية بتقول رقمًا
 * والنظام بيعمل برقم تاني** — وده في ورقة قانونية مش تفصيلة.
 *
 * فالنص بيكتب `{المدة}` و`{مدة_الملفات}`، والرقم بيتحط وقت العرض.
 *
 * ⚠️ **والعلامة المجهولة بتفضل زيّ ما هي** — مابتتشالش. لو الإدارة
 *    كتبت `{حاجة}` بالغلط، تشوفها على الشاشة وتصلّحها؛ أهون من إنها
 *    تختفي في سكوت وتسيب جملة ناقصة.
 *
 * ⚠️ **من غير React** — عشان يتختبر.
 */

export type ContentVars = Record<string, string | number>;

/** `{اسم}` ← القيمة، والمجهول بيفضل مكتوب زيّ ما هو. */
export function fillContentTokens(text: string, vars: ContentVars = {}): string {
  return (text ?? '').replace(/\{([^{}\s]+)\}/g, (match, name: string) =>
    name in vars ? String(vars[name]) : match,
  );
}
