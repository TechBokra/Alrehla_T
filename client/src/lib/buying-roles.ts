import type { UserRole } from '@/types';

/**
 * مين اللي يقدر يطلب من الموقع؟
 *
 * ── القرار ───────────────────────────────────────────────────
 *
 * ملاحظة تامر (١٨ أكتوبر): «عايز أفصل حساب مقدم الخدمة والمدرب
 * والإداري إنه يطلب طلب بنفس الحساب. لو حابب، يبقى يعمل حساب منفصل».
 *
 * ── وده مش تنظيم شكلي ───────────────────────────────────────
 *
 * ⚠️ **الحساب الواحد بدورين بيبهدل الحسابات.** مقدّم الخدمة بياخد
 *    نسبة، وبيقبض من المحفظة، وليه سجل أرباح وسحوبات. ولو نفس الحساب
 *    اشترى، بقى طرفًا في الطلب من الناحيتين: دافع ومستحق. وفي جدول
 *    الأرباح الموحّد مافيش طريقة تفرّق هل الرقم ده عمولته ولا فلوسه
 *    اللي دفعها.
 *
 * ⚠️ **وأسوأ منه: المدرب يحجز مع نفسه.** الحجز بيختار مدربًا، ومافيش
 *    حاجة تمنع إن المدرب هو نفسه الحاجز — فيطلع في كشف الجلسات جلسة
 *    بين الشخص ونفسه، والمستحقات بتتحسب عليها.
 *
 * ⚠️ **والإداري بيراجع الطلبات.** الإداري اللي ليه طلب في النظام
 *    بيقدر يعتمد دفع طلبه هو، ويغيّر حالته، ويلغيه بعد التنفيذ. ومش
 *    اتهام لحد — ده مجرد باب مابينفعش يفضل مفتوح وإحنا بنسجّل تدقيقًا
 *    وبنوزّع فلوسًا.
 *
 * ── الحل: حساب تاني، مش استثناء ─────────────────────────────
 *
 * الواحد عنده حساب شغل وحساب شخصي بإيميل تاني — ودي عادية في أي
 * منصة فيها بايعين ومشترين. والرسالة بتقول ده بالظبط، مش «غير مصرح».
 *
 * ⚠️ **الطالب مسموح له هنا.** حساب الطفل التابع ممنوع بحارس تاني
 *    (`requireNotDependent` + محفّز `block_suspended_purchase`) لأن
 *    سببه مختلف — طلبه بيمر على ولي أمره. ومافيش داعي نكرّره.
 */

/** الأدوار اللي بتشتري. */
export const BUYING_ROLES: readonly UserRole[] = ['customer', 'student'] as const;

/** أسماء الأدوار المحجوبة زي ما العميل يفهمها. */
const STAFF_ROLE_LABELS: Partial<Record<UserRole, string>> = {
  instructor: 'مدرب',
  service_provider: 'مقدّم خدمة',
  publisher: 'دار نشر',
  general_supervisor: 'إداري',
  super_admin: 'مدير نظام',
};

/**
 * الدور ده ممنوع من الطلب؟ `null` = مسموح.
 *
 * ⚠️ **المنطق بالاستبعاد مش بقايمة منع.** لو اتضاف دور جديد في
 *    القاعدة بكرة (مُراجع، مترجم…)، القايمة السودة كانت هتسمح له
 *    بالشراء بالسكوت. كده الدور الجديد بيترفض لحد ما حد يقرّر إنه
 *    بيشتري — والقرار بيبان في السطر ده.
 */
export function staffPurchaseBlock(
  role: UserRole | null | undefined,
): { label: string; message: string } | null {
  if (!role) return null;
  // الزائر بيتعامل معاه حارس تسجيل الدخول — رسالة «اعمل حساب تاني»
  // للزائر مالهاش معنى.
  if (role === 'visitor') return null;
  if (BUYING_ROLES.includes(role)) return null;

  const label = STAFF_ROLE_LABELS[role] ?? 'حساب شغل';
  return {
    label,
    message:
      `حسابك ده حساب ${label} على المنصة، والطلبات بتتعمل من حساب عميل. ` +
      'لو عايز تطلب لنفسك أو لعيالك، اعمل حساب جديد بإيميل تاني وهتقدر تطلب عادي — ' +
      'وحساب الشغل بيفضل زيّ ما هو.',
  };
}
