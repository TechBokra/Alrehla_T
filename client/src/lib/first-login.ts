/**
 * أول دخول: الحساب اتعمل برمز مؤقت، والشخص لازم يحطّ كلمة مروره.
 *
 * ── ليه مش رابط دعوة ────────────────────────────────────────
 *
 * الطريقة القديمة كانت بتولّد **رابط دعوة** تبعته الإدارة للمدرب.
 * الرابط ده مفتاح حساب كامل: أي حد يفتحه يحدّد كلمة المرور. وطوله
 * وشكله بيخلّيه صعب النقل على واتساب، وبينتهي بعد مدة، والمدرب اللي
 * يفتحه متأخر يبقى محتاج دعوة جديدة.
 *
 * الرمز المؤقت أبسط: كلمة مرور عادية **قصيرة العمر عمليًّا** — أول ما
 * المدرب يدخل بيها، الموقع بيوقفه على شاشة واحدة يحطّ فيها كلمة مروره،
 * وما يقدرش يشوف لوحته ولا يعمل أي حاجة قبلها. وبعدها الرمز مابقاش
 * ينفع لأن كلمة المرور اتغيّرت.
 *
 * ── فين العلامة متخزّنة، وليه ───────────────────────────────
 *
 * في `app_metadata` بتاع Supabase Auth — **مش** في `user_metadata`
 * ولا في عمود عندنا.
 *
 * ⚠️ **والفرق ده أمني لا تنظيمي:**
 *
 *   `user_metadata`  ← المستخدم نفسه يقدر يعدّله من المتصفح بنداء
 *                      واحد. يعني كان هيشيل العلامة ويعدّي الشاشة
 *                      وهو لسه على الرمز المؤقت.
 *   `app_metadata`   ← **مفتاح الخدمة وحده** اللي يكتب فيه. المستخدم
 *                      لا يقرأه ولا يغيّره.
 *
 * ولأنها برّه جداولنا، مفيش تعديل قاعدة ولا سياسة جديدة ولا حارس
 * إضافي — والحاجة الوحيدة اللي بتفكّها هي الدالة اللي بتتأكد إن كلمة
 * المرور اتغيّرت فعلًا.
 *
 * ⚠️ **وملاحظة على القراءة:** `supabase.auth.getUser()` بيسأل خادم
 *    المصادقة لا التوكن المخزّن، فالعلامة بتبان محدَّثة فورًا بعد ما
 *    تتشال — من غير ما المستخدم يحتاج يخرج ويدخل.
 */

export const MUST_SET_PASSWORD = 'must_set_password';

/** الشاشة اللي بيتوقف عندها لحد ما يحطّ كلمة مروره. */
export const SET_PASSWORD_PATH = '/set-password';

type WithAppMetadata = { app_metadata?: Record<string, unknown> | null } | null | undefined;

export function needsPasswordSetup(user: WithAppMetadata): boolean {
  return user?.app_metadata?.[MUST_SET_PASSWORD] === true;
}

/**
 * رمز مؤقت للإدارة تبعته بإيدها.
 *
 * ⚠️ **الحروف الملتبسة مشالة عن قصد**: مفيش `l` ولا `I` ولا `1`، ولا
 *    `O` ولا `0`. الرمز ده بيتقال في تليفون أو يتكتب على ورقة، وحرف
 *    ملتبس واحد معناه مكالمة تانية.
 *
 * ⚠️ **ومفيش رموز خاصة**: الرمز بيتنسخ ويتلصق على واتساب، والرموز
 *    الخاصة بتتحوّل أحيانًا في التنسيق التلقائي.
 *
 * 12 خانة من 55 حرفًا ≈ 69 بت — أقوى بكتير من أي كلمة مرور بيكتبها
 * إنسان، وهو مؤقت أصلًا.
 */
export function generateTempCode(): string {
  const alphabet = 'abcdefghijkmnopqrstuvwxyzABCDEFGHJKLMNPQRSTUVWXYZ23456789';
  const bytes = new Uint32Array(12);
  crypto.getRandomValues(bytes);
  // مجموعات من أربعة عشان يتقري ويتقال: xxxx-xxxx-xxxx
  const raw = Array.from(bytes, (b) => alphabet[b % alphabet.length]).join('');
  return `${raw.slice(0, 4)}-${raw.slice(4, 8)}-${raw.slice(8, 12)}`;
}
