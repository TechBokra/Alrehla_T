import type { StatusBadgeType } from '@/components/StatusBadge';

/**
 * حالة تذكرة الدعم — **مصدر واحد للاسم واللون**.
 *
 * ── ليه الملف ده موجود ──────────────────────────────────────
 *
 * نفس الحالة كانت متكتوبة في تلات أماكن، **وبتقول تلات حاجات**:
 *
 *   قايمة التذاكر   : answered → `neutral` · «مُجاب عليها»
 *   صفحة التذكرة    : answered → `success` · «تم الرد»
 *   تفاصيل المستخدم : `{t.status}` — **القيمة الخام من القاعدة**،
 *                     يعني الإداري بيشوف كلمة «answered» إنجليزي
 *
 * ⚠️ **والتالتة دي عطل مش تفاوت**: الشاشة بتعرض اسم عمود في قاعدة
 *    البيانات لمستخدم بيقرا عربي.
 *
 * ⚠️ **ودي نفس القاعدة المسجَّلة عندنا**: الحاجة اللي بتتوصف في
 *    أكتر من مكان بتتناقض — وكل إصلاح بيتعمل في واحدة وينسى
 *    الباقي.
 *
 * ── والاختيار بين `success` و`neutral` ──────────────────────
 *
 * «تم الرد» **مش نجاحًا نهائيًّا**: التذكرة لسه مفتوحة والعميل ممكن
 * يرجع يسأل. النجاح هو **الإغلاق**. فالحالات بقت:
 *
 *   open     → انتظار (محتاجة ردًّا — مش تحذير، ده شغل عادي)
 *   answered → معلومة (اتردّ عليها، ولسه مفتوحة)
 *   closed   → تمام (خلصت)
 *
 * ⚠️ و`open` كانت `warning`. التحذير معناه «فيه حاجة غلط» —
 *    وتذكرة جديدة مش حاجة غلط، دي شغل جاي.
 */

export type TicketStatus = 'open' | 'answered' | 'closed';

export const TICKET_STATUS: Record<
  TicketStatus,
  { label: string; type: StatusBadgeType }
> = {
  open: { label: 'مفتوحة', type: 'pending' },
  answered: { label: 'تم الرد', type: 'info' },
  closed: { label: 'مغلقة', type: 'success' },
};

/**
 * ⚠️ **بترجّع القيمة الخام لو الحالة مش معروفة** بدل ما ترمي أو
 *    تعرض فراغ: لو اتضافت حالة جديدة في القاعدة، الشاشة بتفضل
 *    شغّالة وبتقول الاسم الخام — وده بيبان ويتصلّح، بخلاف الفراغ
 *    اللي بيعدّي من غير ما حد ياخد باله.
 */
export function ticketStatus(status: string): { label: string; type: StatusBadgeType } {
  return TICKET_STATUS[status as TicketStatus] ?? { label: status, type: 'neutral' };
}
