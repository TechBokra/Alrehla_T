-- 03 — أول مدير نظام
-- ============================================================
--
-- ⚠️ **بيتشغّل بعد ما تسجّل حساب على الموقع نفسه** (صفحة «إنشاء حساب»)
--    وتأكّد الإيميل لو اتطلب منك.
--
-- كل حساب جديد بيبدأ «عميل». الملف ده بيرقّي حساب واحد بإيميله لـ«مدير
-- نظام»، ومن لوحة الإدارة بعد كده تقدر تدّي صلاحيات لأي حد تاني.
--
-- ✏️ غيّر الإيميل في السطر اللي تحت للإيميل اللي سجّلت بيه، وبعدين Run.
-- ============================================================

UPDATE public.user_profiles
   SET role = 'super_admin'
 WHERE id = (SELECT id FROM auth.users WHERE lower(email) = lower('اكتب-الإيميل-هنا@example.com'));

-- التأكيد: لازم يطلع سطر واحد دوره super_admin.
-- لو مفيش ولا سطر: الإيميل مكتوب غلط، أو الحساب لسه ما اتعملش على الموقع.
SELECT u.email, p.full_name, p.role
  FROM auth.users u
  JOIN public.user_profiles p ON p.id = u.id
 WHERE p.role = 'super_admin';
