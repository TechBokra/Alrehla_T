-- ============================================================================
-- حالة «مخفي» للمدرب — مش ظاهر على الموقع، وشغّال زي ما هو
-- ============================================================================
-- الحاجة  : الإدارة محتاجة تشيل مدربًا من الموقع **من غير ما توقفه**:
--           مايظهرش للزوار ومايتحجزش عليه جديد، إنما جلساته ومهامه
--           الحالية تفضل وهو يكمّلها عادي من لوحته.
--
--           اللي كان موجود: `pending_training` و`pending_approval` و
--           `active` و`suspended`. ومفيش فيهم «مخفي وشغّال»:
--             • الرجوع لـ`pending_*` بيدّي معنى غلط (لسه ما اتدرّبش)
--               وبيوقف `training_passed` منطقيًّا.
--             • `suspended` معناها عقوبة، والمدرب هيقراها كده.
--
-- الفرق   : `hidden`    = مش ظاهر، مش قابل للحجز، **ولوحته مفتوحة**.
--           `suspended` = مش ظاهر، مش قابل للحجز، وفيها معنى الإيقاف.
--
--           الاتنين مش ظاهرين — لأن الظهور بقى `active` وحدها
--           (`isPubliclyVisible` في الكود).
--
-- ⚠️ **الإخفاء مابيلمسش الشغل القائم ولا الفلوس.** الجلسات المجدولة
--    تفضل، والمستحقات تفضل، وطلب السحب يفضل متاح — المدرب عمل الشغل
--    ده فعلًا. اللي بيقف هو **الجديد** وبس.
--
-- ⚠️ **ومابيتبعتش إشعار للمدرب.** الإخفاء قرار إداري ممكن يكون مؤقتًا
--    (ملف ناقص، إجازة، مراجعة) — وإشعار «اتخفيت» هيقلقه بلا داعٍ.
--    `suspended` هي اللي ليها معنى يتبلّغ.
--
-- الأثر   : قيمة واحدة في `instructor_status_enum`. مفيش صف بيتغيّر،
--           ومفيش سلوك بيتغيّر لحد ما الإدارة تستعملها.
--
-- ⚠️ **`ALTER TYPE ... ADD VALUE` مابينفعش تتستعمل في نفس المعاملة
--    اللي ضافتها.** عشان كده القيمة لوحدها في الملف ده، والكود اللي
--    بيستعملها في النشر اللي بعده.
--
-- التحقق  : تحت.
--
-- الرجوع  : مفيش `DROP VALUE` في بوستجرس. الرجوع = إن الكود مايستعملهاش
--           (والقيمة تفضل في النوع بلا ضرر).
-- ============================================================================

alter type public.instructor_status_enum add value if not exists 'hidden';


