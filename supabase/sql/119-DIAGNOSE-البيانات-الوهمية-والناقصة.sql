-- ============================================================
-- 119 — تشخيص: بيانات وهمية أو ناقصة ظاهرة للزوار  (قراءة فقط)
-- ============================================================
--
-- ✅ **قراءة فقط.** مفيش تعديل ولا حذف ولا صف بيتلمس.
--
-- ── ليه الملف ده ────────────────────────────────────────────
--
-- مسح الكود رجع نضيف: كل نتايج البحث عن «lorem» و«dummy» و«تجريبي»
-- طلعت إما خانات إدخال (`placeholder="مثال: …"`) أو **تعليقات
-- بتوصف حاجة اتشالت خلاص**.
--
-- ⚠️ **لكن الكود مش المكان اللي البيانات الوهمية بتعيش فيه دلوقتي.**
--    بعد ما المحتوى اتنقل للقاعدة، الصفحة العامة بتعرض اللي في
--    الجداول — فالسؤال بقى سؤال قاعدة لا سؤال كود.
--
-- ── تصحيح: النسخة الأولى من الملف ده وقعت ───────────────────
--
-- ⚠️ كتبت قسمًا بيدوّر على منتجات متعلَّمة `is_sample` ومفلترة
--    بـ`is_active`. الاستعلام وقع: **`personalized_products`
--    مافيهوش ولا عمود منهم.**
--
--    العمودان `is_sample` على **`instructors`** و**`publishers`**
--    وبس — أنا قريت اسم العمود في `src/types/supabase.ts` وما
--    شفتش هو تحت أنهي جدول. ودي **نفس الغلطة المسجَّلة عندي
--    مرتين** (دروس §10/9 و§10/13): الحكم على القاعدة من الكود.
--
-- ✅ **والوقعة كشفت حاجة مفيدة:** `personalized_products` **مالوش
--    `is_active` أصلًا** — يعني **مفيش طريقة توقف منتج**. أي صف في
--    الجدول معروض للبيع. القسم ٢ بيسرد المنتجات كلها عشان تتراجع
--    بالعين، لأن مفيش عمود يفلتر بيه.
--
-- ── والأسئلة اللي بنسألها ───────────────────────────────────
--
--   ① مدربون وناشرون متعلَّمين «تجريبي» ولسه ظاهرين
--   ② كل المنتجات (مفيش إيقاف، فكلها معروضة)
--   ③ حقول عامة متسيبة فاضية أو «لاحقًا»
--   ④ أسماء منتجات متكررة بأسعار مختلفة
--   ⑤ الإضافات — للمراجعة بالعين
--   ⑥ نصوص محتوى شبه فاضية (بتمسح الأصلي)
-- ============================================================

SELECT القسم, البند, التفاصيل, الحالة FROM (

  -- ══ ١) مدربون وناشرون متعلَّمين «تجريبي» ═══════════════
  SELECT
    '1. صفوف تجريبية'::text AS القسم,
    ('مدرب: ' || i.display_name)::text AS البند,
    ('الحالة: ' || i.status
      || '  ·  تجريبي: ' || COALESCE(i.is_sample::text, 'فاضي'))::text AS التفاصيل,
    CASE
      WHEN i.is_sample AND i.status = 'active'
        THEN '🔴 نشط وظاهر للزوار بشارة «بيانات تجريبية»'
      WHEN i.is_sample THEN '⚠️ متعلَّم تجريبي بس مش نشط'
      ELSE '✓ حقيقي'
    END AS الحالة
  FROM public.instructors i

  UNION ALL

  SELECT
    '1. صفوف تجريبية',
    ('ناشر: ' || pb.name)::text,
    ('الحالة: ' || COALESCE(pb.status::text, '—')
      || '  ·  تجريبي: ' || COALESCE(pb.is_sample::text, 'فاضي'))::text,
    CASE WHEN pb.is_sample THEN '🔴 ناشر تجريبي' ELSE '✓ حقيقي' END
  FROM public.publishers pb

  UNION ALL

  -- ══ ٢) كل المنتجات ═════════════════════════════════════
  --
  -- ⚠️ **مفيش عمود إيقاف على المنتجات.** يعني كل صف هنا معروض
  --    للبيع دلوقتي، ومفيش طريقة تخفي واحدًا غير إنك تحذفه.
  --
  --    ده مش تفصيلة إدارية: منتج اتعمل للتجربة، أو اتكرر بالغلط،
  --    أو اتقرّر إيقافه — **مالوش مكان يروحه غير الحذف**، والحذف
  --    بيضيّع أي طلب قديم مربوط بيه.
  SELECT
    '2. المنتجات (كلها معروضة)',
    p.name::text,
    ('السعر: ' || COALESCE(p.price::text, '—')
      || '  ·  التصنيف: ' || COALESCE(p.category::text, '—')
      || '  ·  المالك: ' || COALESCE(p.owner_type::text, '—')
      || '  ·  الرابط: ' || COALESCE(p.slug, '—'))::text,
    '⬅️ اقرا الاسم والسعر — مفيش عمود إيقاف يفلتر بيه'
  FROM public.personalized_products p

  UNION ALL

  -- ══ ٣) حقول عامة ناقصة أو متسيبة ═══════════════════════
  --
  -- ⚠️ الزائر مابيعرفش إن الحقل ناقص — بيقراه على إنه المحتوى.
  SELECT
    '3. حقول مدرب ناقصة',
    i.display_name::text,
    ('النبذة: ' || COALESCE(NULLIF(left(btrim(coalesce(i.bio,'')), 40), ''), '— فاضية —')
      || '  ·  التخصصات: '
      || COALESCE(NULLIF(array_to_string(i.specialties, '، '), ''), '— فاضية —'))::text,
    CASE
      WHEN i.status <> 'active' THEN '⚠️ مش نشط — مش ظاهر للزوار'
      WHEN btrim(coalesce(i.bio,'')) = ''
        OR i.bio ILIKE '%لاحق%' OR i.bio ILIKE '%قريب%'
        OR i.specialties IS NULL OR array_length(i.specialties, 1) IS NULL
        OR array_to_string(i.specialties, ' ') ILIKE '%لاحق%'
        THEN '🔴 نشط وظاهر للعامة بحقل ناقص أو «لاحقًا»'
      ELSE '✓ متملّي'
    END
  FROM public.instructors i

  UNION ALL

  -- ══ ٤) أسماء منتجات متكررة ═════════════════════════════
  --
  -- ⚠️ الاسم المتكرر بسعرين مختلفين بيخلّي العميل يشوف نفس
  --    «المنتج» مرتين بفرق تمن — ومايعرفش إيه الفرق.
  SELECT
    '4. أسماء منتجات متكررة',
    x.name::text,
    ('عدد: ' || x.cnt::text || '  ·  الأسعار: ' || x.prices)::text,
    '🔴 نفس الاسم لأكتر من منتج — راجع'
  FROM (
    SELECT p.name,
           count(*) AS cnt,
           string_agg(COALESCE(p.price::text,'—'), ' · ' ORDER BY p.price) AS prices
    FROM public.personalized_products p
    GROUP BY p.name
    HAVING count(*) > 1
  ) x

  UNION ALL

  -- ══ ٥) الإضافات — للمراجعة بالعين ══════════════════════
  --
  -- ⚠️ مفيش استعلام بيعرف إن «منتج جديد» اسم مش منتج. الإنسان
  --    بيعرف في ثانية، فبنسردهم كلهم بدل ما نخمّن.
  SELECT
    '5. الإضافات',
    a.name::text,
    ('السعر: ' || COALESCE(a.price::text,'—')
      || '  ·  نشط: ' || COALESCE(a.is_active::text,'فاضي')
      || '  ·  بيقبل تخصيص: ' || COALESCE(a.supports_customization::text,'فاضي'))::text,
    CASE WHEN a.is_active THEN '⬅️ ظاهر للعملاء — اقرا الاسم' ELSE '✓ موقوف' END
  FROM public.addon_products a

  UNION ALL

  -- ══ ٦) نصوص محتوى شبه فاضية ════════════════════════════
  --
  -- ⚠️ **الفاضي أمان، وشبه الفاضي خطر.** الجدول بيشيل اللي اتعدّل
  --    بس، والفاضي بيرجّع الأصلي من الكود — لكن صف فيه مسافة أو
  --    نقطة بيتعامل كنصّ حقيقي **ويمسح الأصلي** من الصفحة.
  SELECT
    '6. نصوص شبه فاضية',
    sc.key::text,
    ('الطول: ' || length(sc.value)::text || '  ·  «' || sc.value || '»')::text,
    '🔴 هيمسح النص الأصلي في الصفحة'
  FROM public.page_content sc
  WHERE sc.value IS NOT NULL
    AND length(btrim(sc.value)) BETWEEN 1 AND 2

) t ORDER BY القسم, الحالة DESC, البند;

