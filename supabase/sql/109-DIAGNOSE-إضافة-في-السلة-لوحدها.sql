-- ============================================================
-- 109 — تشخيص: إضافة في السلة لوحدها  (قراءة فقط)
-- ============================================================
--
-- ✅ **قراءة فقط.** مفيش سطر بيكتب حاجة.
--
-- ── البلاغ ──────────────────────────────────────────────────
--
-- «إضافة بدون قصة، والزر يقبل أكثر من مرة».
--
-- وفي صفحة «القصص المخصصة» كان تحت كل إضافة زرّ «أضف للسلة».
-- والصورة اللي وصلتني فيها العدّاد على **٣** من ضغطات متكرّرة على
-- نفس الإضافة.
--
-- ── اللي قريته في الكود ─────────────────────────────────────
--
-- `create_customer_order` بتدوّر على كل بند كده:
--
--     SELECT p.id, p.price, p.category
--       FROM personalized_products p
--      WHERE p.id::text = v_item->>'product_id';
--     IF NOT FOUND THEN RAISE EXCEPTION 'منتج غير موجود: %'
--
-- والإضافات في جدول **تاني** اسمه `addon_products`.
--
-- ⚠️ **يعني لو ده صح، الإضافة لوحدها في السلة بترفض الطلب كله** —
--    بالقصص اللي معاها في نفس السلة — والعميل بيشوف «منتج غير
--    موجود: 3f2a-…» وميعرفش يعمل إيه.
--
-- ⚠️ **بس ده استنتاج من الكود، والقاعدة هي مصدر الحقيقة.** الملف ده
--    بيسأل القاعدة مباشرة بدل ما أبني على قراءتي. وقعت في الفخّ ده
--    مرتين في الجلسة دي، فبسأل الأول.
--
-- القسم ١: أرقام الإضافات موجودة في جدول المنتجات ولا لأ؟
-- القسم ٢: هل عدّى طلب فعلًا ببند رقمه رقم إضافة؟
-- ============================================================

SELECT القسم, البند, التفاصيل, الحالة FROM (

  -- ══ ١) الجدولان: بيشتركوا في أرقام؟ ════════════════════
  SELECT
    '1. الجدولان'::text AS القسم,
    a.name::text        AS البند,
    ('رقم الإضافة: ' || a.id::text
      || '  ·  السعر: ' || COALESCE(a.price::text, '—')
      || '  ·  نشطة: ' || CASE WHEN a.is_active THEN 'أيوه' ELSE 'لأ' END)::text
      AS التفاصيل,
    CASE
      WHEN EXISTS (SELECT 1 FROM personalized_products p WHERE p.id::text = a.id::text)
        THEN '⚠️ الرقم ده موجود في المنتجات كمان'
      ELSE '🔴 مش في جدول المنتجات — الطلب بيترفض'
    END AS الحالة
  FROM public.addon_products a

  UNION ALL

  -- ══ ٢) هل عدّى طلب ببند = إضافة؟ ══════════════════════
  --
  -- لو الإجابة «صفر»، يبقى مفيش عميل اتظلم فعلًا — الزرّ كان بيوقّع
  -- الطلب قبل ما يتسجّل. ولو فيه، يبقى في بنود محتاجة مراجعة.
  SELECT
    '2. الطلبات',
    'بنود رقمها رقم إضافة',
    ('عدد البنود: ' || (
        SELECT count(*)::text FROM public.order_items oi
         WHERE EXISTS (SELECT 1 FROM public.addon_products a
                        WHERE a.id::text = oi.product_id::text)
      )
      || '  ·  إجمالي البنود في القاعدة: '
      || (SELECT count(*)::text FROM public.order_items))::text,
    CASE WHEN (
        SELECT count(*) FROM public.order_items oi
         WHERE EXISTS (SELECT 1 FROM public.addon_products a
                        WHERE a.id::text = oi.product_id::text)
      ) = 0
      THEN '✓ مفيش — الطلب كان بيترفض قبل ما يتسجّل'
      ELSE '🔴 فيه بنود محتاجة مراجعة'
    END

  UNION ALL

  -- ══ ٣) الإضافات المتاحة، وبتتعلّق بإيه ════════════════
  --
  -- للتأكّد إن الإضافات اللي في الشاشة هي نفسها اللي في القاعدة.
  SELECT
    '3. الإضافات',
    'addon_products',
    ('العدد: ' || (SELECT count(*)::text FROM public.addon_products)
      || '  ·  النشطة: '
      || (SELECT count(*)::text FROM public.addon_products WHERE is_active)
      || '  ·  بتقبل تخصيص: '
      || (SELECT count(*)::text FROM public.addon_products
           WHERE supports_customization))::text,
    'للمراجعة'

) t ORDER BY القسم, البند;

