-- ============================================================
-- 114 — مسح البيانات التجريبية، وقفل حالة الجلسة
-- ============================================================
--
-- ⚠️⚠️ **الملف ده بيحذف بيانات، والحذف مالوش تراجع.** ⚠️⚠️
--
--    مفيش نسخة احتياطية في الملف ده ومفيش قسم «رجوع». اللي هيتمسح
--    مش هيرجع تاني بأي طريقة من هنا.
--
--    **اقرا الجرد تحت قبل ما تشغّله.**
--
-- ── اللي هيتمسح، بالأرقام اللي ملف 113 طبعها ────────────────
--
--   طلبات المتجر:        8   (ومعاها 8 بنود — CASCADE)
--   اشتراكات الباقات:    7   (ومعاها 60 جلسة و2 تقرير — CASCADE)
--   طلبات الأبناء:       5
--
--   💰 **وبيروح معاهم سجلّ**:
--      69,080 ج.م طلبات (منها 22,700 مدفوعة أو مسلَّمة)
--      52,130 ج.م اشتراكات (منها 14,970 نشطة)
--
-- ⚠️ الأرقام دي **مش فلوس بتترد** — دي سجلّات لطلبات تجريبية.
--    بس لو فيه صف واحد بس حقيقي وسطهم، ده بيروح معاهم.
--    أصحاب الصفوف حسب الجرد: «parent- test» · «محمد حسني» ·
--    «مستخدم جديد» (حسابان). لو كلهم اختبار، كمّل.
--
-- ── اللي **مش** هيتمسح، وده مقصود ───────────────────────────
--
--   • **الحسابات والأطفال** — الحسابات نفسها بتفضل. المسح للمعاملات
--     لا للناس. لو عايز تمسح حسابًا، ده قرار تاني ومن شاشة تانية.
--   • **المنتجات والباقات والمدربين** — دي إعدادات المنصة مش معاملات.
--   • **معرض أعمال الأطفال** — مش مربوط بالاشتراكات.
--
-- ── وحاجتان برّه القاعدة ────────────────────────────────────
--
--   **٢٥ غرفة عند Daily** هتفضل موجودة. **وهي مش بتكلّف حاجة**:
--   Daily بيحاسب بدقيقة المشارك، والغرفة الفاضية بصفر. وكلها ليها
--   تاريخ انتهاء وبتتشال لوحدها. فمفيش داعي لأي تدخّل.
--
--   **١٢ صورة إيصال** على Cloudinary (7 طلبات + 5 اشتراكات) هتبقى
--   بلا رابط. هتبان في شاشة Cloudinary وتتمسح من هناك.
--
-- ── وبعد المسح: قفل حالة الجلسة ─────────────────────────────
--
-- ملف 112 كشف إن `sessions.status` **العمود الوحيد بلا أي حماية**:
-- مفيش `CHECK` ولا نوع معرَّف. والستين جلسة كانت كلها `pending`
-- والافتراضي `scheduled` — يعني قيمة القاعدة نفسها ما كانتش بتتطبّق.
--
-- ⚠️ **وإضافة القيد بعد المسح أأمن من قبله**: الجدول بيبقى فاضي،
--    فمفيش صف يقع عليه القيد. القسم ٤ بيضيفه.
-- ============================================================

BEGIN;

-- ── ١) طلبات المتجر ────────────────────────────────────────
--
-- `order_items` بتمشي وراها بـCASCADE — متأكَّد من الجرد.

DELETE FROM public.orders;

-- ── ٢) اشتراكات الباقات ────────────────────────────────────
--
-- CASCADE بيمشي على: sessions ← session_reports.
-- يعني السطر ده لوحده بيشيل 7 اشتراكات و60 جلسة و2 تقرير.

DELETE FROM public.course_subscriptions;

-- ── ٣) طلبات الأبناء ───────────────────────────────────────
--
-- ⚠️ **لو عايز تسيبها، حط `--` في أول السطر ده وبس.** دي طلبات
--    أطفال لأولياء أمورهم، وكلها من نفس الحسابات التجريبية —
--    بس هي نوع مختلف عن المعاملات فوق، فسايبها في قسم لوحدها.

DELETE FROM public.dependent_requests;

-- ── ٤) حارس حالة الجلسة ────────────────────────────────────
--
-- القايمة من `SessionStatus` في الكود، وهي اللي الشاشات بتترجمها.
-- `scheduled` هي الافتراضي في القاعدة، و`pending` بتفضل مسموحة
-- لأنها حالة حقيقية: جلسة اتعملت ومواعيدها ما اتولدتش.

ALTER TABLE public.sessions
  DROP CONSTRAINT IF EXISTS sessions_status_check;

ALTER TABLE public.sessions
  ADD CONSTRAINT sessions_status_check
  CHECK (status IN ('pending', 'scheduled', 'confirmed', 'completed', 'cancelled'));

-- والتسجيل: تلات حالات وبس، والفراغ مسموح (جلسة بلا تسجيل).

ALTER TABLE public.sessions
  DROP CONSTRAINT IF EXISTS sessions_recording_status_check;

ALTER TABLE public.sessions
  ADD CONSTRAINT sessions_recording_status_check
  CHECK (recording_status IS NULL
         OR recording_status IN ('pending', 'ready', 'deleted'));

-- ── ٥) عدّاد الرقم المرجعي ─────────────────────────────────
--
-- الأرقام المرجعية (ALR-000012) بتتولد من عدّاد، وهو دلوقتي عند
-- رقم عالي بسبب الطلبات التجريبية. تصفيره بيخلّي أول طلب حقيقي
-- يبدأ من ALR-000001.
--
-- ⚠️ **ومفيش خطر تكرار** بعد ما كل الطلبات القديمة اتمسحت.

ALTER SEQUENCE IF EXISTS public.payment_reference_seq RESTART WITH 1;

COMMIT;

-- ============================================================
-- تأكيد — استعلام واحد
-- ============================================================

SELECT القسم, البند, التفاصيل, الحالة FROM (

  SELECT '1. اتمسح'::text AS القسم, 'الجداول'::text AS البند,
         ('طلبات: ' || (SELECT count(*)::text FROM public.orders)
           || '  ·  بنود: ' || (SELECT count(*)::text FROM public.order_items)
           || '  ·  اشتراكات: ' || (SELECT count(*)::text FROM public.course_subscriptions)
           || '  ·  جلسات: ' || (SELECT count(*)::text FROM public.sessions)
           || '  ·  تقارير: ' || (SELECT count(*)::text FROM public.session_reports)
           || '  ·  طلبات أبناء: ' || (SELECT count(*)::text FROM public.dependent_requests))::text
           AS التفاصيل,
         'المفروض كلها صفر'::text AS الحالة

  UNION ALL

  SELECT '2. اللي فضل', 'مش معاملات',
         ('حسابات: ' || (SELECT count(*)::text FROM public.user_profiles)
           || '  ·  أطفال: ' || (SELECT count(*)::text FROM public.child_profiles)
           || '  ·  مدربين: ' || (SELECT count(*)::text FROM public.instructors)
           || '  ·  منتجات: ' || (SELECT count(*)::text FROM public.personalized_products)
           || '  ·  باقات: ' || (SELECT count(*)::text FROM public.creative_writing_packages))::text,
         '✓ ما اتلمستش — دي إعدادات المنصة'

  UNION ALL

  SELECT '3. الحارس', con.conname::text,
         left(pg_get_constraintdef(con.oid), 130)::text,
         '✓ اتضاف'
  FROM pg_constraint con
  JOIN pg_class rel ON rel.oid = con.conrelid
  WHERE rel.relname = 'sessions' AND con.contype = 'c'

  UNION ALL

  SELECT '4. العدّاد', 'payment_reference_seq',
         ('آخر قيمة: ' || COALESCE((SELECT last_value::text
                                      FROM public.payment_reference_seq), '—'))::text,
         'أول طلب جديد هيبقى ALR-000001'

) t ORDER BY القسم, البند;

