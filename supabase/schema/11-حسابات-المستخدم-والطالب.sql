-- ── ٢. حساب الطفل مايشتريش — من القاعدة (بيتعمل الأول) ─────────────────────

CREATE OR REPLACE FUNCTION public.block_suspended_purchase()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
DECLARE
  v_owner uuid;
BEGIN
  -- اسم عمود المالك بيتبعت وقت ربط المحفّز: orders.user_id،
  -- course_subscriptions.user_id، service_orders.buyer_profile_id.
  v_owner := (to_jsonb(NEW) ->> TG_ARGV[0])::uuid;

  IF v_owner IS NULL THEN
    RETURN NEW;
  END IF;

  IF EXISTS (
    SELECT 1 FROM public.user_profiles
     WHERE id = v_owner AND suspended_at IS NOT NULL
  ) THEN
    RAISE EXCEPTION 'الحساب ده موقوف عن الشراء. تواصل مع الإدارة.';
  END IF;

  -- ملف 11: حساب الطفل التابع بيطلب من ولي أمره، مايشتريش بنفسه.
  IF EXISTS (
    SELECT 1 FROM public.child_profiles
     WHERE account_profile_id = v_owner::text
  ) THEN
    RAISE EXCEPTION 'حساب الطالب مايشتريش مباشرة — اطلب من ولي أمرك.';
  END IF;

  RETURN NEW;
END
$function$
;

-- ── ١. الأفراد اللي اتعملوا «طالب» بالغلط ← «حساب مستخدم» ──
-- جملة واحدة: بتصلّح وبتعرض أسماء اللي اتصلّحوا (ممكن تطلع فاضية).
-- حسابات الأطفال الحقيقية (المربوطة بطفل في عيلة) مابتتلمسش.
WITH fixed AS (
  UPDATE public.user_profiles p
     SET role = 'customer', updated_at = now()
   WHERE p.role = 'student'
     AND NOT EXISTS (
       SELECT 1 FROM public.child_profiles c
        WHERE c.account_profile_id = p.id::text
     )
  RETURNING p.full_name
)
SELECT full_name AS "اتحوّل لحساب مستخدم" FROM fixed ORDER BY full_name;
