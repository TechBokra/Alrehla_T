-- ============================================================
-- 11 — الفرق بين «حساب مستخدم» و«حساب الطالب»
-- ============================================================
--
-- ── المشكلة (ملاحظة تامر) ────────────────────────────────────
--
-- «إضافة مستخدم» في لوحة الإدارة كانت بتعمل كل حساب بدور «طالب» —
-- والطالب عندنا = **حساب طفل تابع لولي أمر**. فالفرد اللي الإدارة
-- ضافته كان بيطلع:
--   • لوحته «لوحة المتدرب» بدل «حسابي».
--   • تغيير اسمه «بيروح لولي أمره» — اللي مش موجود.
--   • مايقدرش يفتح «حسابي» (طلباته ومدفوعاته) — المساحة دي مقفولة على
--     حسابات الأطفال.
--
-- الكود اتصلّح (الإدارة بتعمل «حساب مستخدم»). الملف ده بيصلّح
-- الحسابات اللي اتعملت غلط قبل كده، وبيقفل ثغرة:
--
-- ١) كل حساب دوره «طالب» **ومش مربوط بطفل** في أي عيلة ← «حساب مستخدم».
--    (حسابات الأطفال الحقيقية مابتتلمسش.)
--
-- ٢) 🔴 **حساب الطفل كان يقدر يشتري لو نادى القاعدة مباشرة.** منع
--    الشراء على حسابات الأطفال كان في الكود بس. دلوقتي القاعدة نفسها
--    بترفض أي طلب أو اشتراك صاحبه حساب طفل — جوّه نفس الحارس اللي بيمنع
--    الحساب الموقوف. (طلب الطفل بيروح لولي أمره، وولي الأمر هو صاحب
--    الطلب — فده مابيتأثرش.)
--
-- ⚠️ مفيش مسح لأي بيانات. تغيير دور + توسيع حارس.
--
-- ── التشغيل ──────────────────────────────────────────────────
--
-- بعد ملف 10. في SQL Editor → Run. (لو اتشغّل تاني مابيضرّش.)
--
-- ⚠️ نسخة أولى كانت بتستعمل جدول مؤقت — ومحرّر Supabase ممكن ينفّذ كل
--    جملة على اتصال لوحده، فالجدول المؤقت «مش موجود» في الجملة اللي
--    بعدها (خطأ 42P01) والملف كله اترفض من غير ما يغيّر حاجة. النسخة
--    دي من غير جداول مؤقتة، وكل جزء فيها جملة واحدة كاملة.
-- ============================================================

